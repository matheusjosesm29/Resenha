def sort_titles(titles, order):
    if order == 'top_rated':
        return sorted(titles, key=lambda t: (-t[3], t[0]))
    elif order == 'random':
        items = list(titles)
        random.shuffle(items)
        return items
    elif order == 'year_desc':
        return sorted(titles, key=lambda t: (-t[1], t[0]))
    elif order == 'year_asc':
        return sorted(titles, key=lambda t: (t[1], t[0]))
    elif order == 'alpha':
        return sorted(titles, key=lambda t: t[0].lower())
    return titles


def main():
    parser = argparse.ArgumentParser(description='Import 999 titles from OMDb into Django DB')
    parser.add_argument('--order', choices=['top_rated','random','year_desc','year_asc','alpha'], default='top_rated')
    parser.add_argument('--delay', type=float, default=0.5, help='Delay between requests (seconds)')
    parser.add_argument('--count', type=int, default=999, help='Max new records to insert')
    parser.add_argument('--dry-run', action='store_true', help='Do not write to DB')
    args = parser.parse_args()

    titles = sort_titles(TITLES_DB, args.order)
    total_titles = len(titles)
    print(f'Total na lista: {total_titles} | Alvo: {args.count} novos | Ordem: {args.order} | Delay: {args.delay}s')

    inserted = 0
    skipped = 0
    errors = 0
    processed = 0

    for title, year, media_type, score in titles:
        if inserted >= args.count:
            break

        processed += 1
        try:
            data = lookup_omdb(title=title)
            imdb_id = data['imdb_id']

            if Work.objects.filter(imdb_id=imdb_id).exists():
                skipped += 1
                print(f'  [skip] {title} ({year}) - ja existe [imdb:{imdb_id}]')
                continue

            if not args.dry_run:
                Work.objects.create(**data)
            inserted += 1
            poster = data.get('poster') or 'NONE'
            print(f'  [ok]   {title} ({year}) - {data["category"]} [imdb:{imdb_id}] poster: {poster[:50]}...')

        except Exception as e:
            errors += 1
            print(f'  [err]  {title} ({year}) - {e}')

        time.sleep(args.delay)

    print(f'\n=== RESUMO ===')
    print(f'Inseridos: {inserted}')
    print(f'Pulados (ja existiam): {skipped}')
    print(f'Erros: {errors}')
    print(f'Total processado: {processed}')
    print(f'Registros totais no banco: {Work.objects.count()}')


if __name__ == '__main__':
    main()
